    PARTLY_CLOUDY_LIGHT_RAIN, PARTLY_CLOUDY_MODERATE_RAIN, PARTLY_CLOUDY_HEAVY_RAIN,
    MOSTLY_CLOUDY_LIGHT_RAIN, MOSTLY_CLOUDY_MODERATE_RAIN, MOSTLY_CLOUDY_HEAVY_RAIN,
    LIGHT_RAIN, MODERATE_RAIN, HEAVY_RAIN,
    ISOLATED_LIGHT_SLEET_SHOWERS, ISOLATED_MODERATE_SLEET_SHOWERS, ISOLATED_HEAVY_SLEET_SHOWERS,
