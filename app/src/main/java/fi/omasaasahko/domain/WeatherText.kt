    FREEZING_FOG, LIGHT_DRIZZLE, MODERATE_DRIZZLE, DENSE_DRIZZLE,
    LIGHT_FREEZING_DRIZZLE, DENSE_FREEZING_DRIZZLE, LIGHT_FREEZING_RAIN, HEAVY_FREEZING_RAIN, SNOW_GRAINS,
    LIGHT_RAIN_SHOWERS, MODERATE_RAIN_SHOWERS, HEAVY_RAIN_SHOWERS, LIGHT_SNOW_SHOWERS, HEAVY_SNOW_SHOWERS,
